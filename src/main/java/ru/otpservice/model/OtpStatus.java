package ru.otpservice.model;

/**
 * Статус одноразового кода
 *   ACTIVE  — код только сгенерирован и ещё не использован, не истёк по времени
 *   EXPIRED — срок жизни кода истёк (выставляется фоновой задачей OtpExpirationScheduler
 *   либо при попытке валидации просроченного кода)
 *   USED — код прошёл валидацию и был использован, повторно его применить нельзя
 */
public enum OtpStatus {
    ACTIVE,
    EXPIRED,
    USED
}
